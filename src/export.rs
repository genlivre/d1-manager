/// Result of parsing MySQL dump
#[derive(Debug, Clone)]
pub struct MySqlConversionResult {
    pub statements: Vec<String>,
    pub warnings: Vec<String>,
    pub tables_found: Vec<String>,
    pub insert_count: usize,
}

/// Parse and convert MySQL dump to SQLite-compatible statements
pub fn parse_mysql_dump(content: &str) -> Result<MySqlConversionResult, String> {
    let mut statements = Vec::new();
    let mut warnings = Vec::new();
    let mut tables_found = Vec::new();
    let mut insert_count = 0;

    // Split into individual statements
    let raw_statements = split_sql_statements(content);

    for stmt in raw_statements {
        let stmt = stmt.trim();
        if stmt.is_empty() {
            continue;
        }

        let upper = stmt.to_uppercase();

        // Skip MySQL-specific commands that SQLite doesn't support
        if upper.starts_with("SET ")
            || upper.starts_with("/*!") && upper.contains("*/")
            || upper.starts_with("LOCK TABLES")
            || upper.starts_with("UNLOCK TABLES")
            || upper.starts_with("START TRANSACTION")
            || upper.starts_with("COMMIT")
            || upper.starts_with("ROLLBACK")
            || upper.starts_with("USE ")
            || upper.starts_with("DROP DATABASE")
            || upper.starts_with("CREATE DATABASE")
            || upper.starts_with("ALTER DATABASE")
        {
            continue;
        }

        // Handle CREATE TABLE
        if upper.starts_with("CREATE TABLE") {
            match convert_create_table(stmt) {
                Ok((converted, table_name)) => {
                    tables_found.push(table_name);
                    statements.push(converted);
                }
                Err(e) => {
                    warnings.push(format!("Skipped CREATE TABLE: {}", e));
                }
            }
            continue;
        }

        // Handle DROP TABLE (convert to DROP TABLE IF EXISTS)
        if upper.starts_with("DROP TABLE") {
            let converted = convert_drop_table(stmt);
            statements.push(converted);
            continue;
        }

        // Handle INSERT statements
        if upper.starts_with("INSERT") {
            match convert_insert(stmt) {
                Ok(converted) => {
                    insert_count += 1;
                    statements.push(converted);
                }
                Err(e) => {
                    warnings.push(format!("Skipped INSERT: {}", e));
                }
            }
            continue;
        }

        // Handle CREATE INDEX
        if upper.starts_with("CREATE INDEX") || upper.starts_with("CREATE UNIQUE INDEX") {
            match convert_create_index(stmt) {
                Ok(converted) => {
                    statements.push(converted);
                }
                Err(e) => {
                    warnings.push(format!("Skipped INDEX: {}", e));
                }
            }
            continue;
        }

        // Skip other unsupported statements
        if upper.starts_with("ALTER TABLE")
            || upper.starts_with("CREATE TRIGGER")
            || upper.starts_with("CREATE VIEW")
            || upper.starts_with("CREATE PROCEDURE")
            || upper.starts_with("CREATE FUNCTION")
        {
            warnings.push(format!("Skipped unsupported: {}", &stmt[..stmt.len().min(50)]));
            continue;
        }
    }

    if statements.is_empty() {
        return Err("No convertible SQL statements found in MySQL dump".to_string());
    }

    Ok(MySqlConversionResult {
        statements,
        warnings,
        tables_found,
        insert_count,
    })
}

/// Split SQL content into individual statements, handling string literals
fn split_sql_statements(content: &str) -> Vec<String> {
    let mut statements = Vec::new();
    let mut current = String::new();
    let mut in_string = false;
    let mut string_char = ' ';
    let mut in_comment = false;
    let mut prev_char = ' ';

    for c in content.chars() {
        // Handle multi-line comments
        if !in_string && prev_char == '/' && c == '*' {
            in_comment = true;
            current.pop(); // Remove the '/'
            prev_char = c;
            continue;
        }
        if in_comment {
            if prev_char == '*' && c == '/' {
                in_comment = false;
            }
            prev_char = c;
            continue;
        }

        // Handle single-line comments
        if !in_string && prev_char == '-' && c == '-' {
            current.pop(); // Remove the first '-'
            // Skip until newline
            prev_char = c;
            continue;
        }

        if in_string {
            current.push(c);
            // Handle escaped quotes
            if c == string_char && prev_char != '\\' {
                in_string = false;
            }
        } else {
            match c {
                '\'' | '"' | '`' => {
                    in_string = true;
                    string_char = c;
                    current.push(c);
                }
                ';' => {
                    let stmt = current.trim().to_string();
                    if !stmt.is_empty() {
                        statements.push(stmt);
                    }
                    current = String::new();
                }
                '\n' | '\r' => {
                    current.push(' ');
                }
                _ => current.push(c),
            }
        }
        prev_char = c;
    }

    // Handle final statement without semicolon
    let final_stmt = current.trim().to_string();
    if !final_stmt.is_empty() {
        statements.push(final_stmt);
    }

    statements
}

/// Convert MySQL CREATE TABLE to SQLite
fn convert_create_table(stmt: &str) -> Result<(String, String), String> {
    // Extract table name
    let re_table = regex_lite::Regex::new(r"(?i)CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?[`'\x22]?(\w+)[`'\x22]?")
        .map_err(|e| e.to_string())?;

    let table_name = re_table
        .captures(stmt)
        .and_then(|c| c.get(1))
        .map(|m| m.as_str().to_string())
        .ok_or("Could not extract table name")?;

    // Find the column definitions section (between first ( and last ))
    let start_paren = stmt.find('(').ok_or("No opening parenthesis found")?;
    let end_paren = stmt.rfind(')').ok_or("No closing parenthesis found")?;

    if start_paren >= end_paren {
        return Err("Invalid CREATE TABLE structure".to_string());
    }

    let columns_section = &stmt[start_paren + 1..end_paren];
    let converted_columns = convert_column_definitions(columns_section)?;

    let result = format!(
        "CREATE TABLE IF NOT EXISTS \"{}\" (\n{}\n)",
        table_name,
        converted_columns
    );

    Ok((result, table_name))
}

/// Convert MySQL column definitions to SQLite
fn convert_column_definitions(columns_section: &str) -> Result<String, String> {
    let mut result_columns = Vec::new();
    let mut primary_keys = Vec::new();
    let mut unique_constraints = Vec::new();

    // Split by comma, but handle nested parentheses
    let column_defs = split_column_definitions(columns_section);

    for col_def in column_defs {
        let col_def = col_def.trim();
        if col_def.is_empty() {
            continue;
        }

        let upper = col_def.to_uppercase();

        // Handle PRIMARY KEY constraint
        if upper.starts_with("PRIMARY KEY") {
            if let Some(keys) = extract_key_columns(col_def) {
                primary_keys.extend(keys);
            }
            continue;
        }

        // Handle UNIQUE constraint
        if upper.starts_with("UNIQUE KEY") || upper.starts_with("UNIQUE INDEX") || upper.starts_with("UNIQUE (") {
            if let Some(keys) = extract_key_columns(col_def) {
                unique_constraints.push(keys);
            }
            continue;
        }

        // Handle KEY/INDEX (skip for SQLite - handle separately)
        if upper.starts_with("KEY ") || upper.starts_with("INDEX ") {
            continue;
        }

        // Handle FOREIGN KEY (simplified - skip complex constraints)
        if upper.starts_with("FOREIGN KEY") || upper.starts_with("CONSTRAINT") {
            continue;
        }

        // Handle FULLTEXT, SPATIAL indexes (not supported in SQLite)
        if upper.starts_with("FULLTEXT") || upper.starts_with("SPATIAL") {
            continue;
        }

        // Regular column definition
        if let Some(converted) = convert_single_column(col_def) {
            result_columns.push(converted);
        }
    }

    // Add primary key constraint if needed
    if !primary_keys.is_empty() && primary_keys.len() > 1 {
        result_columns.push(format!(
            "  PRIMARY KEY ({})",
            primary_keys.iter().map(|k| format!("\"{}\"", k)).collect::<Vec<_>>().join(", ")
        ));
    }

    // Add unique constraints
    for keys in unique_constraints {
        if keys.len() == 1 {
            // Single column unique - should be in column definition
            continue;
        }
        result_columns.push(format!(
            "  UNIQUE ({})",
            keys.iter().map(|k| format!("\"{}\"", k)).collect::<Vec<_>>().join(", ")
        ));
    }

    Ok(result_columns.join(",\n"))
}

/// Split column definitions handling nested parentheses
fn split_column_definitions(section: &str) -> Vec<String> {
    let mut result = Vec::new();
    let mut current = String::new();
    let mut paren_depth = 0;
    let mut in_string = false;
    let mut string_char = ' ';

    for c in section.chars() {
        if in_string {
            current.push(c);
            if c == string_char {
                in_string = false;
            }
            continue;
        }

        match c {
            '\'' | '"' | '`' => {
                in_string = true;
                string_char = c;
                current.push(c);
            }
            '(' => {
                paren_depth += 1;
                current.push(c);
            }
            ')' => {
                paren_depth -= 1;
                current.push(c);
            }
            ',' if paren_depth == 0 => {
                result.push(current.trim().to_string());
                current = String::new();
            }
            _ => current.push(c),
        }
    }

    if !current.trim().is_empty() {
        result.push(current.trim().to_string());
    }

    result
}

/// Convert a single column definition from MySQL to SQLite
fn convert_single_column(col_def: &str) -> Option<String> {
    let parts: Vec<&str> = col_def.split_whitespace().collect();
    if parts.is_empty() {
        return None;
    }

    // Extract column name (remove backticks/quotes)
    let col_name = parts[0].trim_matches(|c| c == '`' || c == '\'' || c == '"');

    if parts.len() < 2 {
        return Some(format!("  \"{}\" TEXT", col_name));
    }

    // Extract and convert data type
    let mut idx = 1;
    let data_type_raw = parts[idx];
    let sqlite_type = convert_mysql_type(data_type_raw);
    idx += 1;

    // Handle type with size specification like VARCHAR(255)
    if data_type_raw.contains('(') {
        // Type already includes size, continue
    } else if idx < parts.len() && parts[idx].starts_with('(') {
        // Skip size specification
        while idx < parts.len() && !parts[idx].contains(')') {
            idx += 1;
        }
        if idx < parts.len() {
            idx += 1;
        }
    }

    // Build column definition
    let mut result = format!("  \"{}\" {}", col_name, sqlite_type);

    // Process remaining parts for constraints
    let remaining = parts[idx..].join(" ").to_uppercase();

    if remaining.contains("NOT NULL") {
        result.push_str(" NOT NULL");
    }

    if remaining.contains("PRIMARY KEY") {
        result.push_str(" PRIMARY KEY");
    }

    if remaining.contains("AUTOINCREMENT") || remaining.contains("AUTO_INCREMENT") {
        // SQLite uses INTEGER PRIMARY KEY for auto-increment
        if !result.contains("PRIMARY KEY") {
            result = result.replace(&sqlite_type, "INTEGER PRIMARY KEY");
        }
    }

    if remaining.contains("UNIQUE") && !remaining.contains("UNIQUE KEY") {
        result.push_str(" UNIQUE");
    }

    // Handle DEFAULT
    if let Some(default_pos) = remaining.find("DEFAULT") {
        let after_default = &remaining[default_pos + 7..].trim_start();
        if let Some(default_value) = extract_default_value(after_default) {
            result.push_str(&format!(" DEFAULT {}", default_value));
        }
    }

    Some(result)
}

/// Extract default value from remaining string
fn extract_default_value(s: &str) -> Option<String> {
    let s = s.trim();
    if s.is_empty() {
        return None;
    }

    // Handle quoted strings
    if s.starts_with('\'') {
        if let Some(end) = s[1..].find('\'') {
            return Some(format!("'{}'", &s[1..end + 1]));
        }
    }

    // Handle NULL
    if s.starts_with("NULL") {
        return Some("NULL".to_string());
    }

    // Handle numbers
    let word: String = s.chars().take_while(|c| c.is_alphanumeric() || *c == '.' || *c == '-').collect();
    if !word.is_empty() {
        if word.parse::<f64>().is_ok() || word.to_uppercase() == "TRUE" || word.to_uppercase() == "FALSE" {
            return Some(word);
        }
    }

    None
}

/// Convert MySQL data type to SQLite type
fn convert_mysql_type(mysql_type: &str) -> &'static str {
    let upper = mysql_type.to_uppercase();
    let base_type = upper.split('(').next().unwrap_or(&upper);

    match base_type {
        // Integer types
        "TINYINT" | "SMALLINT" | "MEDIUMINT" | "INT" | "INTEGER" | "BIGINT" => "INTEGER",
        "BOOL" | "BOOLEAN" => "INTEGER",

        // Floating point
        "FLOAT" | "DOUBLE" | "DECIMAL" | "NUMERIC" | "REAL" => "REAL",

        // Text types
        "CHAR" | "VARCHAR" | "TINYTEXT" | "TEXT" | "MEDIUMTEXT" | "LONGTEXT" => "TEXT",
        "ENUM" | "SET" => "TEXT",

        // Binary types
        "BINARY" | "VARBINARY" | "TINYBLOB" | "BLOB" | "MEDIUMBLOB" | "LONGBLOB" => "BLOB",

        // Date/time types - store as TEXT in SQLite
        "DATE" | "TIME" | "DATETIME" | "TIMESTAMP" | "YEAR" => "TEXT",

        // JSON - store as TEXT
        "JSON" => "TEXT",

        // Default
        _ => "TEXT",
    }
}

/// Extract column names from KEY definition
fn extract_key_columns(key_def: &str) -> Option<Vec<String>> {
    let start = key_def.find('(')?;
    let end = key_def.rfind(')')?;

    if start >= end {
        return None;
    }

    let columns_str = &key_def[start + 1..end];
    let columns: Vec<String> = columns_str
        .split(',')
        .map(|s| {
            let s = s.trim();
            // Remove backticks and any size specification like (255)
            let name = s.split('(').next().unwrap_or(s);
            name.trim_matches(|c| c == '`' || c == '\'' || c == '"').to_string()
        })
        .filter(|s| !s.is_empty())
        .collect();

    if columns.is_empty() {
        None
    } else {
        Some(columns)
    }
}

/// Convert DROP TABLE statement
fn convert_drop_table(stmt: &str) -> String {
    let re = regex_lite::Regex::new(r"(?i)DROP\s+TABLE\s+(?:IF\s+EXISTS\s+)?[`'\x22]?(\w+)")
        .ok();

    if let Some(re) = re {
        if let Some(caps) = re.captures(stmt) {
            if let Some(table_name) = caps.get(1) {
                return format!("DROP TABLE IF EXISTS \"{}\"", table_name.as_str());
            }
        }
    }

    // Fallback: just make it IF EXISTS
    stmt.replace("DROP TABLE ", "DROP TABLE IF EXISTS ")
}

/// Convert INSERT statement (handle backticks, etc.)
fn convert_insert(stmt: &str) -> Result<String, String> {
    // Replace backticks with double quotes for identifiers
    let converted = stmt
        .replace('`', "\"")
        // Handle MySQL's INSERT IGNORE
        .replace("INSERT IGNORE", "INSERT OR IGNORE");

    Ok(converted)
}

/// Convert CREATE INDEX statement
fn convert_create_index(stmt: &str) -> Result<String, String> {
    // Replace backticks with double quotes
    let converted = stmt.replace('`', "\"");
    Ok(converted)
}

