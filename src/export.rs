#![allow(dead_code)]

use serde_json::Value;
use std::io::Write;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ExportFormat {
    Csv,
    Json,
    Sql,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ImportFormat {
    Csv,
    Json,
    Sql,
    MySqlDump,
}

impl ImportFormat {
    pub fn extension(&self) -> &'static str {
        match self {
            ImportFormat::Csv => "csv",
            ImportFormat::Json => "json",
            ImportFormat::Sql => "sql",
            ImportFormat::MySqlDump => "sql",
        }
    }

    pub fn description(&self) -> &'static str {
        match self {
            ImportFormat::Csv => "CSV - First row as column headers",
            ImportFormat::Json => "JSON - Array of objects",
            ImportFormat::Sql => "SQL - Execute statements directly",
            ImportFormat::MySqlDump => "MySQL Dump - Convert to SQLite",
        }
    }

    pub fn all() -> &'static [ImportFormat] {
        &[
            ImportFormat::Csv,
            ImportFormat::Json,
            ImportFormat::Sql,
            ImportFormat::MySqlDump,
        ]
    }
}

/// Conflict resolution strategy for imports
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ConflictStrategy {
    Fail,    // Abort on duplicate
    Replace, // UPDATE existing rows (INSERT OR REPLACE)
    Skip,    // Ignore duplicates (INSERT OR IGNORE)
}

impl ConflictStrategy {
    pub fn description(&self) -> &'static str {
        match self {
            ConflictStrategy::Fail => "Fail on conflict",
            ConflictStrategy::Replace => "Replace existing rows",
            ConflictStrategy::Skip => "Skip duplicates",
        }
    }

    pub fn sql_keyword(&self) -> &'static str {
        match self {
            ConflictStrategy::Fail => "INSERT INTO",
            ConflictStrategy::Replace => "INSERT OR REPLACE INTO",
            ConflictStrategy::Skip => "INSERT OR IGNORE INTO",
        }
    }
}

impl ExportFormat {
    pub fn extension(&self) -> &'static str {
        match self {
            ExportFormat::Csv => "csv",
            ExportFormat::Json => "json",
            ExportFormat::Sql => "sql",
        }
    }

    pub fn description(&self) -> &'static str {
        match self {
            ExportFormat::Csv => "CSV (Comma Separated Values)",
            ExportFormat::Json => "JSON (JavaScript Object Notation)",
            ExportFormat::Sql => "SQL (INSERT statements)",
        }
    }
}

/// Export table data to CSV format
pub fn export_to_csv(columns: &[String], rows: &[Vec<Value>]) -> String {
    let mut output = String::new();

    // Header row
    output.push_str(&columns.iter()
        .map(|c| escape_csv_field(c))
        .collect::<Vec<_>>()
        .join(","));
    output.push('\n');

    // Data rows
    for row in rows {
        let line: Vec<String> = row.iter()
            .map(|v| escape_csv_field(&value_to_string(v)))
            .collect();
        output.push_str(&line.join(","));
        output.push('\n');
    }

    output
}

/// Export table data to JSON format
pub fn export_to_json(columns: &[String], rows: &[Vec<Value>]) -> String {
    let records: Vec<serde_json::Map<String, Value>> = rows.iter()
        .map(|row| {
            columns.iter()
                .zip(row.iter())
                .map(|(col, val)| (col.clone(), val.clone()))
                .collect()
        })
        .collect();

    serde_json::to_string_pretty(&records).unwrap_or_else(|_| "[]".to_string())
}

/// Export table data to SQL INSERT statements
pub fn export_to_sql(table_name: &str, columns: &[String], rows: &[Vec<Value>]) -> String {
    let mut output = String::new();

    // Header comment
    output.push_str(&format!("-- Export of table: {}\n", table_name));
    output.push_str(&format!("-- Rows: {}\n", rows.len()));
    output.push_str("-- Generated by D1 Manager\n\n");

    if rows.is_empty() {
        output.push_str("-- No data to export\n");
        return output;
    }

    // Generate INSERT statements
    let columns_str = columns.iter()
        .map(|c| format!("\"{}\"", c))
        .collect::<Vec<_>>()
        .join(", ");

    for row in rows {
        let values: Vec<String> = row.iter()
            .map(|v| value_to_sql(v))
            .collect();

        output.push_str(&format!(
            "INSERT INTO \"{}\" ({}) VALUES ({});\n",
            table_name,
            columns_str,
            values.join(", ")
        ));
    }

    output
}

/// Export full database schema and data (SQL dump)
pub fn export_database_dump(
    tables: &[(String, Vec<String>, Vec<Vec<Value>>)],
    schema_sql: &[(String, String)], // (table_name, create_statement)
) -> String {
    let mut output = String::new();

    output.push_str("-- D1 Database Dump\n");
    output.push_str("-- Generated by D1 Manager\n");
    output.push_str(&format!("-- Date: {}\n\n", chrono_now()));
    output.push_str("PRAGMA foreign_keys=OFF;\n");
    output.push_str("BEGIN TRANSACTION;\n\n");

    // Schema (CREATE TABLE statements)
    for (table_name, create_sql) in schema_sql {
        output.push_str(&format!("-- Table: {}\n", table_name));
        output.push_str(create_sql);
        if !create_sql.ends_with(';') {
            output.push(';');
        }
        output.push_str("\n\n");
    }

    // Data
    for (table_name, columns, rows) in tables {
        if !rows.is_empty() {
            output.push_str(&format!("-- Data for table: {}\n", table_name));
            output.push_str(&export_to_sql(table_name, columns, rows));
            output.push('\n');
        }
    }

    output.push_str("COMMIT;\n");
    output.push_str("PRAGMA foreign_keys=ON;\n");

    output
}

/// Escape a field for CSV format
fn escape_csv_field(field: &str) -> String {
    if field.contains(',') || field.contains('"') || field.contains('\n') || field.contains('\r') {
        format!("\"{}\"", field.replace('"', "\"\""))
    } else {
        field.to_string()
    }
}

/// Convert JSON value to string for display
fn value_to_string(value: &Value) -> String {
    match value {
        Value::Null => String::new(),
        Value::Bool(b) => b.to_string(),
        Value::Number(n) => n.to_string(),
        Value::String(s) => s.clone(),
        Value::Array(arr) => serde_json::to_string(arr).unwrap_or_default(),
        Value::Object(obj) => serde_json::to_string(obj).unwrap_or_default(),
    }
}

/// Convert JSON value to SQL literal
fn value_to_sql(value: &Value) -> String {
    match value {
        Value::Null => "NULL".to_string(),
        Value::Bool(b) => if *b { "1" } else { "0" }.to_string(),
        Value::Number(n) => n.to_string(),
        Value::String(s) => format!("'{}'", s.replace('\'', "''")),
        Value::Array(arr) => format!("'{}'", serde_json::to_string(arr).unwrap_or_default().replace('\'', "''")),
        Value::Object(obj) => format!("'{}'", serde_json::to_string(obj).unwrap_or_default().replace('\'', "''")),
    }
}

/// Get current timestamp as string
fn chrono_now() -> String {
    use std::time::{SystemTime, UNIX_EPOCH};
    let secs = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);

    // Simple ISO-like format without external crate
    let days = secs / 86400;
    let years = 1970 + days / 365;
    format!("{}-XX-XX", years)
}

/// Save content to file using file dialog
pub fn save_to_file(content: &str, default_name: &str, extension: &str) -> Result<std::path::PathBuf, String> {
    let file_path = rfd::FileDialog::new()
        .set_file_name(&format!("{}.{}", default_name, extension))
        .add_filter(extension.to_uppercase(), &[extension])
        .add_filter("All Files", &["*"])
        .save_file()
        .ok_or_else(|| "Export cancelled".to_string())?;

    let mut file = std::fs::File::create(&file_path)
        .map_err(|e| format!("Failed to create file: {}", e))?;

    file.write_all(content.as_bytes())
        .map_err(|e| format!("Failed to write file: {}", e))?;

    Ok(file_path)
}

