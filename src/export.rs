/// Result of parsing an import file
#[derive(Debug, Clone)]
pub struct ImportData {
    pub columns: Vec<String>,
    pub rows: Vec<Vec<Value>>,
}

/// Open file picker and read content
pub fn pick_and_read_file(format: ImportFormat) -> Result<(String, String), String> {
    let extensions: &[&str] = match format {
        ImportFormat::Csv => &["csv", "txt"],
        ImportFormat::Json => &["json"],
        ImportFormat::Sql => &["sql"],
        ImportFormat::MySqlDump => &["sql", "dump"],
    };

    let file_path = rfd::FileDialog::new()
        .add_filter(format.extension().to_uppercase(), extensions)
        .add_filter("All Files", &["*"])
        .pick_file()
        .ok_or_else(|| "Import cancelled".to_string())?;

    let content = std::fs::read_to_string(&file_path)
        .map_err(|e| format!("Failed to read file: {}", e))?;

    let filename = file_path
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or("unknown")
        .to_string();

    Ok((content, filename))
}

/// Parse CSV content into columns and rows
pub fn parse_csv(content: &str) -> Result<ImportData, String> {
    let mut lines = content.lines().peekable();

    // Parse header
    let header_line = lines.next().ok_or("CSV file is empty")?;
    let columns: Vec<String> = parse_csv_line(header_line);

    if columns.is_empty() {
        return Err("No columns found in CSV header".to_string());
    }

    // Parse data rows
    let mut rows = Vec::new();
    for line in lines {
        if line.trim().is_empty() {
            continue;
        }

        let values = parse_csv_line(line);
        let row: Vec<Value> = values
            .into_iter()
            .map(|s| {
                if s.is_empty() {
                    Value::Null
                } else if let Ok(n) = s.parse::<i64>() {
                    Value::Number(n.into())
                } else if let Ok(n) = s.parse::<f64>() {
                    Value::Number(serde_json::Number::from_f64(n).unwrap_or_else(|| 0.into()))
                } else if s.eq_ignore_ascii_case("true") {
                    Value::Bool(true)
                } else if s.eq_ignore_ascii_case("false") {
                    Value::Bool(false)
                } else if s.eq_ignore_ascii_case("null") {
                    Value::Null
                } else {
                    Value::String(s)
                }
            })
            .collect();

        // Pad with nulls if row is shorter than header
        let mut padded_row = row;
        while padded_row.len() < columns.len() {
            padded_row.push(Value::Null);
        }

        rows.push(padded_row);
    }

    Ok(ImportData { columns, rows })
}

/// Parse a single CSV line handling quoted fields
fn parse_csv_line(line: &str) -> Vec<String> {
    let mut fields = Vec::new();
    let mut current = String::new();
    let mut in_quotes = false;
    let mut chars = line.chars().peekable();

    while let Some(c) = chars.next() {
        if in_quotes {
            if c == '"' {
                if chars.peek() == Some(&'"') {
                    // Escaped quote
                    current.push('"');
                    chars.next();
                } else {
                    // End of quoted field
                    in_quotes = false;
                }
            } else {
                current.push(c);
            }
        } else {
            match c {
                '"' => in_quotes = true,
                ',' => {
                    fields.push(current.trim().to_string());
                    current = String::new();
                }
                _ => current.push(c),
            }
        }
    }

    fields.push(current.trim().to_string());
    fields
}

/// Parse JSON content into columns and rows
pub fn parse_json(content: &str) -> Result<ImportData, String> {
    let data: Vec<serde_json::Map<String, Value>> = serde_json::from_str(content)
        .map_err(|e| format!("Invalid JSON: {}", e))?;

    if data.is_empty() {
        return Err("JSON array is empty".to_string());
    }

    // Collect all unique column names from all objects
    let mut column_set = std::collections::HashSet::new();
    for obj in &data {
        for key in obj.keys() {
            column_set.insert(key.clone());
        }
    }

    let columns: Vec<String> = column_set.into_iter().collect();

    // Build rows
    let rows: Vec<Vec<Value>> = data
        .iter()
        .map(|obj| {
            columns
                .iter()
                .map(|col| obj.get(col).cloned().unwrap_or(Value::Null))
                .collect()
        })
        .collect();

    Ok(ImportData { columns, rows })
}

/// Parse SQL file and extract statements
pub fn parse_sql(content: &str) -> Result<Vec<String>, String> {
    let mut statements = Vec::new();
    let mut current = String::new();
    let mut in_string = false;
    let mut string_char = ' ';

    for c in content.chars() {
        if in_string {
            current.push(c);
            if c == string_char {
                in_string = false;
            }
        } else {
            match c {
                '\'' | '"' => {
                    in_string = true;
                    string_char = c;
                    current.push(c);
                }
                ';' => {
                    let stmt = current.trim().to_string();
                    if !stmt.is_empty() && !stmt.starts_with("--") {
                        statements.push(stmt);
                    }
                    current = String::new();
                }
                '-' if current.ends_with('-') => {
                    // Skip single-line comments
                    current.pop();
                    // Skip until newline
                }
                '\n' => {
                    if !current.trim().starts_with("--") {
                        current.push(' ');
                    } else {
                        current = String::new();
                    }
                }
                _ => current.push(c),
            }
        }
    }

    // Handle final statement without semicolon
    let final_stmt = current.trim().to_string();
    if !final_stmt.is_empty() && !final_stmt.starts_with("--") {
        statements.push(final_stmt);
    }

    if statements.is_empty() {
        return Err("No SQL statements found".to_string());
    }

    Ok(statements)
}

/// Generate INSERT statements from import data
pub fn generate_insert_statements(
    table_name: &str,
    data: &ImportData,
    strategy: ConflictStrategy,
) -> Vec<String> {
    let columns_str = data.columns
        .iter()
        .map(|c| format!("\"{}\"", c))
        .collect::<Vec<_>>()
        .join(", ");

    let insert_keyword = strategy.sql_keyword();

    data.rows
        .iter()
        .map(|row| {
            let values: Vec<String> = row.iter().map(value_to_sql).collect();
            format!(
                "{} \"{}\" ({}) VALUES ({});",
                insert_keyword,
                table_name,
                columns_str,
                values.join(", ")
            )
        })
        .collect()
}

